"""
Analytic benchmark for the k=0 Poisson solver.

Compares the numerical potential generated by a normalized hydrogenic 1s
orbital with its analytic Coulomb potential, and separates:
  1. Poisson-solver error;
  2. integration/interpolation error in the final Coulomb integral.

Run from the project root:
    python -m tests.test_poisson_potential

If the tests directory is not a package, run:
    python tests/test_poisson_potential.py
"""

from __future__ import annotations

import numpy as np

from grid.mesh import make_atomic_mesh
from integrals.poisson import (
    _transition_charge,
    solve_poisson_orbital_pair,
    integrate_orbital_pair_potential,
)


# ---------------------------------------------------------------------------
# Benchmark parameters
# ---------------------------------------------------------------------------

Z = 4.0
B = 0.0
K = 0
QUADRATURE_ORDER = 8

GRID_SIZES = (40, 60, 80, 120, 160)

A_RHO = 1.0
A_Z = 1.0
MAPPING_B = 0.5
T_RHO_MAX = 0.98
T_Z_MAX = 0.98

EXACT_COULOMB_INTEGRAL = 5.0 * Z / 8.0


# ---------------------------------------------------------------------------
# Analytic reference
# ---------------------------------------------------------------------------

def hydrogenic_1s(rho: np.ndarray, z: np.ndarray, nuclear_charge: float) -> np.ndarray:
    """Radial part psi(rho,z) for phi=(2*pi)^(-1/2)*psi, normalized in rho drho dz."""
    radius = np.sqrt(rho[:, None] ** 2 + z[None, :] ** 2)
    return np.sqrt(2.0 * nuclear_charge**3) * np.exp(-nuclear_charge * radius)


def analytic_1s_potential(
    rho: np.ndarray,
    z: np.ndarray,
    nuclear_charge: float,
) -> np.ndarray:
    r"""
    Coulomb potential of a normalized hydrogenic 1s density:

        V(r) = [1 - (1 + Z*r)*exp(-2*Z*r)] / r,

    with V(0)=Z.  The expression is evaluated in a cancellation-resistant
    form near the origin.
    """
    radius = np.sqrt(rho[:, None] ** 2 + z[None, :] ** 2)
    x = nuclear_charge * radius

    potential = np.empty_like(radius, dtype=np.float64)
    small = x < 1.0e-4
    regular = ~small

    # Series: Z * (1 - 2*x^2/3 + 2*x^3/3 - 2*x^4/5 + O(x^5)).
    xs = x[small]
    potential[small] = nuclear_charge * (
        1.0
        - (2.0 / 3.0) * xs**2
        + (2.0 / 3.0) * xs**3
        - (2.0 / 5.0) * xs**4
    )

    xr = x[regular]
    rr = radius[regular]
    numerator = -np.expm1(-2.0 * xr) - xr * np.exp(-2.0 * xr)
    potential[regular] = numerator / rr

    return potential


def integrate_axisymmetric_grid(
    values: np.ndarray,
    rho_nodes: np.ndarray,
    z_nodes: np.ndarray,
) -> float:
    """Approximate integral int rho * values(rho,z) d(rho) d(z) by trapezoids."""
    along_z = np.trapezoid(values, z_nodes, axis=1)
    return float(np.trapezoid(rho_nodes * along_z, rho_nodes))


def weighted_potential_errors(
    numerical: np.ndarray,
    exact: np.ndarray,
    rho_nodes: np.ndarray,
    z_nodes: np.ndarray,
) -> tuple[float, float, tuple[int, int]]:
    """Return max error, rho-weighted RMS error, and grid index of max error."""
    difference = np.asarray(numerical).real - exact
    absolute = np.abs(difference)
    max_index = np.unravel_index(np.argmax(absolute), absolute.shape)

    denominator = integrate_axisymmetric_grid(
        np.ones_like(exact), rho_nodes, z_nodes
    )
    numerator = integrate_axisymmetric_grid(
        difference**2, rho_nodes, z_nodes
    )
    rms = np.sqrt(numerator / denominator) if denominator > 0.0 else np.nan

    return float(np.max(absolute)), float(rms), max_index


# ---------------------------------------------------------------------------
# One grid calculation
# ---------------------------------------------------------------------------

def run_grid(n_rho: int, n_z: int) -> dict:
    rho_mesh, z_mesh = make_atomic_mesh(
        n_rho=n_rho,
        n_z=n_z,
        A_rho=A_RHO,
        A_z=A_Z,
        b=MAPPING_B,
        t_rho_max=T_RHO_MAX,
        t_z_max=T_Z_MAX,
    )

    rho_nodes = np.asarray(rho_mesh.physical, dtype=np.float64)
    z_nodes = np.asarray(z_mesh.physical, dtype=np.float64)

    psi = hydrogenic_1s(rho_nodes, z_nodes, Z)

    # Normalize with exactly the same quadrature convention as the Poisson code.
    norm = _transition_charge(
        orbital_q=psi,
        orbital_s=psi,
        rho_nodes=rho_nodes,
        z_nodes=z_nodes,
        quadrature_order=QUADRATURE_ORDER,
    )
    norm = complex(norm)
    if abs(norm.imag) > 1.0e-11:
        raise RuntimeError(f"Unexpected imaginary orbital norm: {norm}")
    if norm.real <= 0.0:
        raise RuntimeError(f"Non-positive orbital norm: {norm}")

    psi = psi / np.sqrt(norm.real)

    normalized_norm = _transition_charge(
        orbital_q=psi,
        orbital_s=psi,
        rho_nodes=rho_nodes,
        z_nodes=z_nodes,
        quadrature_order=QUADRATURE_ORDER,
    )

    # Numerical Poisson solution for the 1s -> 1s transition density.
    potential_numerical = solve_poisson_orbital_pair(
        orbital_q=psi,
        orbital_s=psi,
        k=K,
        rho_nodes=rho_nodes,
        z_nodes=z_nodes,
        quadrature_order=QUADRATURE_ORDER,
    )
    potential_numerical = np.asarray(potential_numerical)

    # Exact potential sampled at the FEM nodes.
    potential_exact = analytic_1s_potential(rho_nodes, z_nodes, Z)

    # Compare potentials directly at all grid nodes.
    max_error, rms_error, max_index = weighted_potential_errors(
        potential_numerical,
        potential_exact,
        rho_nodes,
        z_nodes,
    )

    i_max, j_max = max_index
    max_error_location = (
        float(rho_nodes[i_max]),
        float(z_nodes[j_max]),
    )

    # Same orbital and same integration routine in both cases.  Only the
    # potential changes, so their difference isolates the Poisson-potential
    # contribution to the final integral.
    g_numerical_potential = integrate_orbital_pair_potential(
        orbital_p=psi,
        orbital_r=psi,
        potential=potential_numerical,
        rho_nodes=rho_nodes,
        z_nodes=z_nodes,
        quadrature_order=QUADRATURE_ORDER,
    )
    g_analytic_potential = integrate_orbital_pair_potential(
        orbital_p=psi,
        orbital_r=psi,
        potential=potential_exact,
        rho_nodes=rho_nodes,
        z_nodes=z_nodes,
        quadrature_order=QUADRATURE_ORDER,
    )

    g_numerical_potential = complex(g_numerical_potential)
    g_analytic_potential = complex(g_analytic_potential)

    # Decomposition:
    # g_num - g_exact = (g_num - g_analytic-grid) + (g_analytic-grid - g_exact).
    poisson_contribution = (
        g_numerical_potential.real - g_analytic_potential.real
    )
    integration_contribution = (
        g_analytic_potential.real - EXACT_COULOMB_INTEGRAL
    )

    return {
        "grid": f"{n_rho}x{n_z}",
        "n_fem": (n_rho - 1) * (n_z - 1),
        "norm": complex(normalized_norm),
        "potential_min": float(np.min(potential_numerical.real)),
        "potential_max": float(np.max(potential_numerical.real)),
        "potential_max_error": max_error,
        "potential_rms_error": rms_error,
        "max_error_location": max_error_location,
        "g_poisson": g_numerical_potential.real,
        "g_analytic_grid": g_analytic_potential.real,
        "g_total_error": g_numerical_potential.real - EXACT_COULOMB_INTEGRAL,
        "g_poisson_contribution": poisson_contribution,
        "g_integration_contribution": integration_contribution,
    }


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------

def main() -> None:
    print("=" * 112)
    print("HYDROGENIC 1s: POINTWISE POISSON POTENTIAL BENCHMARK")
    print("=" * 112)
    print(f"Z = {Z:g}")
    print(f"k = {K}")
    print(f"Quadrature order = {QUADRATURE_ORDER}")
    print(f"Exact Coulomb integral = {EXACT_COULOMB_INTEGRAL:.12f} Ha")
    print()

    results = []
    for n in GRID_SIZES:
        result = run_grid(n, n)
        results.append(result)

    print(
        f"{'Grid':>10} {'Norm':>14} {'max|dV|':>14} "
        f"{'RMS(dV)':>14} {'g[Poisson]':>16} {'g[analytic V]':>16}"
    )
    print("-" * 112)
    for result in results:
        print(
            f"{result['grid']:>10} "
            f"{result['norm'].real:14.10f} "
            f"{result['potential_max_error']:14.6e} "
            f"{result['potential_rms_error']:14.6e} "
            f"{result['g_poisson']:16.10f} "
            f"{result['g_analytic_grid']:16.10f}"
        )

    print()
    print("ERROR DECOMPOSITION")
    print("-" * 112)
    print(
        f"{'Grid':>10} {'Total error':>16} {'Poisson part':>16} "
        f"{'Integration part':>20} {'max-error point (rho,z)':>28}"
    )
    print("-" * 112)
    for result in results:
        rho_max, z_max = result["max_error_location"]
        print(
            f"{result['grid']:>10} "
            f"{result['g_total_error']:16.6e} "
            f"{result['g_poisson_contribution']:16.6e} "
            f"{result['g_integration_contribution']:20.6e} "
            f"({rho_max:.5g}, {z_max:.5g})"
        )

    print()
    print("POTENTIAL RANGE")
    print("-" * 112)
    for result in results:
        print(
            f"{result['grid']:>10}: "
            f"V_min={result['potential_min']:.8e}, "
            f"V_max={result['potential_max']:.8e}"
        )

    print()
    print("Interpretation:")
    print("  g[Poisson] - g[analytic V] isolates the effect of the numerical Poisson potential.")
    print("  g[analytic V] - 5Z/8 measures the remaining quadrature/interpolation error")
    print("  for the same discretized orbital and the same final integration routine.")
    print("=" * 112)


if __name__ == "__main__":
    main()
